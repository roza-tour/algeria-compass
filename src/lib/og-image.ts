/** Path to the preview card for a page. `hint` is extra text to match on --
 *  a question page passes its category, read after the slug and title. */
export function ogFallback(pathname: string, title = '', hint = ''): string {
  const text = `${pathname} ${title} ${hint}`;
  const key = RULES.find(([, re]) => re.test(text))?.[0] ?? 'default';
  return `/assets/img/og/${key}.jpg`;
}

// Phase B — generate src/styles/civ-skins.css from src/data/civSkins.mjs.
// Each skin -> a [data-civ="0X"] block: token overrides, tiling background +
// faint emblem watermark, themed hero overlay, patterned section dividers,
// emblem heading markers, and accent card/gallery frames. Dark skins also get
// light-on-dark content overrides so text stays AA-readable.
import { writeFileSync } from 'node:fs';
import { SKINS } from '../src/data/civSkins.mjs';

const hexToRgb = h => { const n = h.replace('#',''); return [0,2,4].map(i => parseInt(n.slice(i,i+2),16)); };
const rgba = (h,a) => { const [r,g,b]=hexToRgb(h); return `rgba(${r},${g},${b},${a})`; };
const shade = (h,t) => { const [r,g,b]=hexToRgb(h).map(v=>Math.round(v*(1-t))); return `rgb(${r},${g},${b})`; };
const shadeA = (h,t,a) => { const [r,g,b]=hexToRgb(h).map(v=>Math.round(v*(1-t))); return `rgba(${r},${g},${b},${a})`; };

// resolve CCC->accent, DDD->accent2 (DDD first), then make a CSS data-URI
const resolve = (svg, s, colorFor) => svg.replaceAll('DDD', colorFor.accent2).replaceAll('CCC', colorFor.accent);
const dataUri = svg => `data:image/svg+xml,${encodeURIComponent(svg)}`;

let css = `/* AUTO-GENERATED by scripts/gen-civ-skins.mjs — do not edit by hand.
   Phase B civilisation skins. Applied via [data-civ] on <html>. */\n`;

for (const s of SKINS) {
  const sel = `[data-civ="${s.id}"]`;
  const patternUri = dataUri(resolve(s.pattern, s, { accent: s.accent, accent2: s.accent2 }));
  const markUri    = dataUri(resolve(s.emblem,  s, { accent: s.accent, accent2: s.accent2 }));
  // watermark: emblem in faint accent
  const wmColor = rgba(s.accent, s.dark ? 0.07 : 0.06);
  const watermarkUri = dataUri(resolve(s.emblem, s, { accent: wmColor, accent2: rgba(s.accent2, 0.06) }));

  css += `\n/* ===== Skin ${s.id} — ${s.name} ===== */\n`;
  css += `${sel}{--accent:${s.accent};--accent-2:${s.accent2};--accent-deep:${shade(s.accent,0.35)};`
       + `--civ-surface:${s.surface};--civ-ink:${s.ink};--wash:${s.dark ? 'rgba(255,255,255,.06)' : rgba(s.accent,0.07)};}\n`;
  // page background: faint emblem watermark (fixed) + tiling pattern
  css += `${sel} body{background-color:${s.surface};`
       + `background-image:url("${watermarkUri}"),url("${patternUri}");`
       + `background-repeat:no-repeat,repeat;`
       + `background-position:right -28px bottom -28px,top left;`
       + `background-size:340px 340px,${s.pw}px ${s.ph}px;`
       + `background-attachment:fixed,scroll;}\n`;
  // themed hero overlay (keeps white hero text readable)
  const ov = s.dark ? shade(s.surface, 0.25) : shade(s.accent, 0.74);
  css += `${sel} .hero::after{background:linear-gradient(90deg,${cssRgba(ov,0.86)},${cssRgba(ov,0.26)} 72%);}\n`;
  // patterned section divider between content sections
  css += `${sel} .section + .section{position:relative;}\n`;
  css += `${sel} .section + .section::before{content:"";position:absolute;left:50%;top:0;transform:translateX(-50%);`
       + `width:min(92%,1100px);height:14px;background:url("${patternUri}") repeat-x center/auto 14px;opacity:.5;}\n`;
  // emblem heading marker + accent underline
  css += `${sel} .prose h2{padding-bottom:.18rem;border-bottom:2px solid ${rgba(s.accent,0.35)};}\n`;
  css += `${sel} .prose h2::before{content:"";display:inline-block;width:.92em;height:.92em;margin-right:.45em;`
       + `vertical-align:-.1em;background:url("${markUri}") center/contain no-repeat;}\n`;
  // accent frames on cards & gallery figures
  css += `${sel} .card{border-color:${rgba(s.accent,0.3)};border-top:3px solid var(--accent);}\n`;
  css += `${sel} .pgrid figure{border-color:${rgba(s.accent,0.4)};}\n`;
  css += `${sel} .qbox{background:${rgba(s.accent, s.dark ? 0.0 : 0.07)};}\n`;

  if (s.dark) {
    const cream = s.ink, soft = rgba(s.ink, 0.62), softer = rgba(s.ink, 0.5);
    const body2 = rgba(s.ink, 0.86);
    const panel = 'rgba(255,255,255,.055)', line = 'rgba(255,255,255,.13)';
    const cardBg = shade(s.surface, -0.12); // slightly lighter than surface
    css += `/* dark-skin content (AA light-on-dark) */\n`;
    css += `${sel} body{color:${body2};}\n`;
    css += `${sel} h1,${sel} h2,${sel} h3,${sel} h4{color:${cream};}\n`;
    css += `${sel} .prose{color:${body2};}\n`;
    css += `${sel} .prose h2,${sel} .prose h3{color:${s.accent};}\n`;
    css += `${sel} a{color:${s.accent};}\n`;
    css += `${sel} .crumbs,${sel} .byline,${sel} .ed-k,${sel} .sources-note,${sel} .pgrid figcaption{color:${soft};}\n`;
    css += `${sel} .byline a,${sel} .ed-v a,${sel} .sources a{color:${s.accent};}\n`;
    css += `${sel} .card{background:${cardBg};border-color:${rgba(s.accent,0.32)};}\n`;
    css += `${sel} .card h3{color:${cream};}${sel} .card p{color:${body2};}${sel} .card .tag,${sel} .card .meta{color:${soft};border-color:${line};}\n`;
    css += `${sel} .facts{background:${panel};border-color:${rgba(s.accent,0.22)};}${sel} .facts td{color:${body2};border-color:${line};}${sel} .facts td:first-child{color:${soft};}\n`;
    css += `${sel} .qbox{color:${body2};}\n`;
    css += `${sel} .pgrid figure{background:${cardBg};}\n`;
    css += `${sel} .sources,${sel} .ed-meta,${sel} .entity-snapshot,${sel} .key-takeaways,${sel} .related,${sel} .def-grid div{background:${panel};border-color:${line};color:${body2};}\n`;
    css += `${sel} .ed-meta{border-left-color:${s.accent};}\n`;
    css += `${sel} .sources ol,${sel} .sources li,${sel} .es-desc,${sel} .es-facts dd{color:${body2};}\n`;
    css += `${sel} .el-group li a{background:${panel};border-color:${line};color:${body2};}\n`;
    css += `${sel} .faq summary{color:${cream};}${sel} .faq p{color:${body2};}${sel} .faq details{border-color:${line};}\n`;
    css += `${sel} .chips-list span{background:${panel};border-color:${line};color:${body2};}\n`;
    // tour pages carry their own per-tour accent + custom selectors — keep them legible on dark
    css += `${sel} .tour-lead,${sel} .tour-highlights li,${sel} .itinerary p,${sel} .why-grid span,${sel} .gtk dd,${sel} .map-route,${sel} .facts li{color:${body2};}\n`;
    css += `${sel} .itinerary strong,${sel} .why-grid strong{color:${cream};}\n`;
    css += `${sel} .tour h2,${sel} .facts h3,${sel} .gtk dt{color:${s.accent};}\n`;
    css += `${sel} .tour-map{border-color:${line};}\n`;
  }
}

// helper used above (needs to handle rgb()/rgba string from shade)
function cssRgba(rgbStr, a) {
  const [r,g,b] = rgbStr.match(/\d+/g);
  return `rgba(${r},${g},${b},${a})`;
}

writeFileSync('src/styles/civ-skins.css', css);
console.log(`[gen] wrote src/styles/civ-skins.css (${SKINS.length} skins, ${css.length} bytes)`);

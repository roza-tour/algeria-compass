// Generate src/styles/civ-skins.css from src/data/civSkins.mjs.
//
// Redesigned October 2026. The eight civilisation skins used to repaint the
// whole tour page: a full-page surface colour (navy for Tuareg & Sahara), a
// tiling pattern under every paragraph, a corner watermark, patterned strips
// between sections and a hand-drawn emblem before every heading. The owner
// judged all eight "primitive", and the dark skin needed 25+ override rules to
// keep its text legible -- the source of several contrast bugs.
//
// Every skin is now light: the site's own paper with a whisper of the
// civilisation's colour. Its art (src/data/civArt.mjs, redrawn the same month)
// is kept and placed where it reads as design rather than clutter -- never
// under the body text:
//   - the hero carries the civilisation's pattern behind the copy;
//   - section breaks are a band of the pattern with the emblem on a seal;
//   - each section heading carries the emblem and a short rule;
//   - a faint emblem watermark sits in the corner.
// Also:
//   - the hero is tinted with the civilisation's ink (Tuareg indigo for the
//     Sahara, terracotta for the Amazigh, teal for Ottoman Algiers...);
//   - cards and photographs take a thin accent edge.
import { writeFileSync, mkdirSync } from 'node:fs';
import { SKINS } from '../src/data/civSkins.mjs';

const hexToRgb = h => { const n = h.replace('#', ''); return [0, 2, 4].map(i => parseInt(n.slice(i, i + 2), 16)); };
const toHex = rgb => '#' + rgb.map(v => Math.round(v).toString(16).padStart(2, '0')).join('');
const rgba = (h, a) => { const [r, g, b] = hexToRgb(h); return `rgba(${r},${g},${b},${a})`; };
const shadeHex = (h, t) => toHex(hexToRgb(h).map(v => v * (1 - t)));
// the site's paper (#FBF8F2) with t of the colour mixed in
const PAPER = [251, 248, 242];
const paper = (h, t) => toHex(PAPER.map((p, i) => p * (1 - t) + hexToRgb(h)[i] * t));
const lum = h => { const f = v => { v /= 255; return v <= .03928 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }; const [r, g, b] = hexToRgb(h).map(f); return .2126 * r + .7152 * g + .0722 * b; };
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + .05) / (y + .05); };
// darken an accent, keeping its hue, until it holds 4.5:1 as text on its paper
const legible = (h, bg) => { let t = 0, c = h; while (contrast(c, bg) < 4.5 && t < .8) { t += .04; c = shadeHex(h, t); } return c; };

const mixWhite = (h, t) => toHex(hexToRgb(h).map(v => v + (255 - v) * t));
const resolve = (svg, c1, c2) => svg.replaceAll('DDD', c2).replaceAll('CCC', c1);
// the art goes to small files, not data URIs: this stylesheet loads on every
// page, and four inlined SVGs per skin took it from 12 KB to 48 KB
mkdirSync('public/assets/civ', { recursive: true });
const file = (name, svg) => { writeFileSync(`public/assets/civ/${name}.svg`, svg); return `url('/assets/civ/${name}.svg')`; };

let css = `/* AUTO-GENERATED by scripts/gen-civ-skins.mjs — do not edit by hand.
   Civilisation skins, applied via [data-civ] on <html>. Light editorial
   pages; identity carried by the hero tint, hairlines and accents. */\n`;

for (const s of SKINS) {
  const sel = `[data-civ="${s.id}"]`;
  const bg = '#FFFFFF';                                      // white paper: the tinted papers read as beige (owner: "old")
  const ink = legible(s.accent, bg);                         // the accent, safe as text on that paper
  const hero = s.dark ? s.surface : shadeHex(s.accent, 0.7); // the civilisation's ink for the hero

  css += `\n/* ===== Skin ${s.id} — ${s.name} ===== */\n`;
  // :root lifts these to (0,2,0) so the season's html[data-season] (0,1,1) does not override them
  css += `:root${sel}{--accent:${ink};--accent-2:${s.accent2};--accent-deep:${shadeHex(s.accent, 0.35)};`
       + `--civ-surface:${bg};--civ-ink:#141414;--civ-hero:${hero};--wash:${rgba(s.accent, 0.06)};}\n`;
  css += `${sel} body{background-color:${bg};}\n`;

  // hero: the photograph tinted with the civilisation's ink, strongest under the copy
  // :root again: html[data-season] .hero::after (0,2,2) would otherwise win
  css += `:root${sel} .hero::after{background:linear-gradient(180deg,transparent calc(100% - 44px),${bg}),`
       + `linear-gradient(100deg,${rgba(hero, 0.9)} 0%,${rgba(hero, 0.55)} 48%,${rgba(hero, 0.18)} 82%),`
       + `linear-gradient(0deg,${rgba(hero, 0.75)},transparent 42%);}\n`;

  const light = mixWhite(s.accent, 0.55);
  const patLight = file(`${s.id}-pattern-light`, resolve(s.pattern, light, mixWhite(s.accent2, 0.5)).replace(/opacity='[.\d]+'/, "opacity='.42'"));
  const patInk = file(`${s.id}-pattern`, resolve(s.pattern, s.accent, s.accent2));
  const emblem = file(`${s.id}-emblem`, resolve(s.emblem, ink, s.accent2));
  const watermark = file(`${s.id}-watermark`, resolve(s.emblem, s.accent, s.accent2).replace("<svg ", "<svg opacity='.07' "));

  // hero: the civilisation's pattern over the tint, strongest behind the copy,
  // fading out toward the photograph (replaces the site-wide compass field)
  // On its own layer (the picture's ::after, absolutely placed against .hero)
  // so the season's sky on .hero::before stays; z-index 2 puts it above the
  // civilisation tint (.hero::after, z 1) and below the copy (z 3).
  css += `:root${sel} .hero > picture::after{content:"";position:absolute;inset:0;z-index:2;pointer-events:none;`
       + `background:${patLight} 0 0/${s.pw * 1.4}px ${s.ph * 1.4}px repeat;`
       + `-webkit-mask-image:linear-gradient(100deg,#000 0%,rgba(0,0,0,.6) 40%,transparent 75%);mask-image:linear-gradient(100deg,#000 0%,rgba(0,0,0,.6) 40%,transparent 75%);}`;

  // section break: a band of the pattern, the emblem on a seal at its centre
  css += `${sel} .section + .section{position:relative;}\n`;
  css += `${sel} .section + .section::before{content:"";position:absolute;left:50%;top:0;transform:translate(-50%,-50%);`
       + `width:min(90%,1040px);height:26px;pointer-events:none;background:${patInk} center/auto 26px repeat-x;`
       + `-webkit-mask-image:linear-gradient(90deg,transparent,#000 22%,transparent 44%,transparent 56%,#000 78%,transparent);`
       + `mask-image:linear-gradient(90deg,transparent,#000 22%,transparent 44%,transparent 56%,#000 78%,transparent);}\n`;
  css += `${sel} .section + .section::after{content:"";position:absolute;left:50%;top:0;transform:translate(-50%,-50%);`
       + `width:46px;height:46px;border-radius:50%;pointer-events:none;background:${bg} ${emblem} center/30px 30px no-repeat;`
       + `box-shadow:0 0 0 1px ${rgba(s.accent, 0.35)},0 0 0 5px ${bg},0 0 0 6px ${rgba(s.accent, 0.18)};}\n`;

  // headings: the civilisation's mark, then a short rule in its colour
  css += `${sel} :is(.prose,.tour) h2::before{content:"";display:block;width:74px;height:26px;margin-bottom:.6rem;`
       + `background:${emblem} left center/26px 26px no-repeat,linear-gradient(${s.accent},${s.accent}) 34px center/40px 2px no-repeat;}\n`;

  // a faint emblem watermark in the corner, on its own fixed layer (composited,
  // unlike background-attachment:fixed, which repainted the page every frame)
  css += `${sel} body::after{content:"";position:fixed;right:-40px;bottom:-40px;width:300px;height:300px;z-index:-1;pointer-events:none;`
       + `background:${watermark} center/contain no-repeat;}\n`;

  // thin accent edges
  css += `${sel} .card{border-top:2px solid ${s.accent};}\n`;
  css += `${sel} .pgrid figure{border-color:${rgba(s.accent, 0.3)};}\n`;
  css += `${sel} .qbox{background:${rgba(s.accent, 0.06)};}\n`;
}

writeFileSync('src/styles/civ-skins.css', css);
console.log(`[gen] wrote src/styles/civ-skins.css (${SKINS.length} skins, ${css.length} bytes)`);
